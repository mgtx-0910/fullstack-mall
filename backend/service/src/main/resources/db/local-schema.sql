DROP TABLE IF EXISTS mall_payment;
DROP TABLE IF EXISTS mall_order_item;
DROP TABLE IF EXISTS mall_order;
DROP TABLE IF EXISTS mall_cart_item;
DROP TABLE IF EXISTS mall_product_sku;
DROP TABLE IF EXISTS mall_product;
DROP TABLE IF EXISTS mall_category;
DROP TABLE IF EXISTS mall_user;

CREATE TABLE mall_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    nickname VARCHAR(50) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role_code VARCHAR(20) NOT NULL DEFAULT 'USER',
    status TINYINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP(3) NOT NULL,
    updated_at TIMESTAMP(3) NOT NULL,
    CONSTRAINT uk_mall_user_username UNIQUE (username)
);

CREATE INDEX idx_mall_user_status_created_at
    ON mall_user (status, created_at);


CREATE TABLE mall_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    status TINYINT NOT NULL DEFAULT 1,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(3) NOT NULL,
    updated_at TIMESTAMP(3) NOT NULL,
    CONSTRAINT uk_mall_category_name UNIQUE (name)
);

CREATE INDEX idx_mall_category_status_sort
    ON mall_category (status, sort_order);

CREATE TABLE mall_product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL,
    title VARCHAR(100) NOT NULL,
    subtitle VARCHAR(100) NOT NULL DEFAULT '',
    description VARCHAR(2000),
    status_code VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP(3) NOT NULL,
    updated_at TIMESTAMP(3) NOT NULL
);

CREATE INDEX idx_mall_product_category_id
    ON mall_product (category_id);
CREATE INDEX idx_mall_product_status_created_at
    ON mall_product (status_code, created_at);
CREATE INDEX idx_mall_product_created_by
    ON mall_product (created_by);


CREATE TABLE mall_product_sku (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    sku_code VARCHAR(64) NOT NULL,
    spec_text VARCHAR(200) NOT NULL,
    sale_price DECIMAL(12,2) NOT NULL,
    available_stock INT NOT NULL DEFAULT 0,
    locked_stock INT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(3) NOT NULL,
    updated_at TIMESTAMP(3) NOT NULL,
    CONSTRAINT uk_mall_product_sku_code UNIQUE (sku_code),
    CONSTRAINT chk_mall_product_sku_price CHECK (sale_price > 0),
    CONSTRAINT chk_mall_product_sku_available_stock CHECK (available_stock >= 0),
    CONSTRAINT chk_mall_product_sku_locked_stock CHECK (locked_stock >= 0),
    CONSTRAINT chk_mall_product_sku_version CHECK (version >= 0)
);

CREATE INDEX idx_mall_product_sku_product_id
    ON mall_product_sku (product_id);


CREATE TABLE mall_cart_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    quantity INT NOT NULL,
    checked TINYINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP(3) NOT NULL,
    updated_at TIMESTAMP(3) NOT NULL,
    CONSTRAINT uk_mall_cart_item_user_sku UNIQUE (user_id, sku_id),
    CONSTRAINT chk_mall_cart_item_quantity CHECK (quantity BETWEEN 1 AND 99),
    CONSTRAINT chk_mall_cart_item_checked CHECK (checked IN (0, 1))
);

CREATE INDEX idx_mall_cart_item_user_updated_at
    ON mall_cart_item (user_id, updated_at);

CREATE TABLE mall_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL,
    status_code VARCHAR(30) NOT NULL,
    total_amount DECIMAL(12,2) NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL,
    updated_at TIMESTAMP(3) NOT NULL,
    expires_at TIMESTAMP(3) NOT NULL,
    paid_at TIMESTAMP(3),
    cancelled_at TIMESTAMP(3),
    closed_at TIMESTAMP(3),
    CONSTRAINT uk_mall_order_order_no UNIQUE (order_no),
    CONSTRAINT uk_mall_order_user_idempotency UNIQUE (user_id, idempotency_key),
    CONSTRAINT chk_mall_order_total_amount CHECK (total_amount >= 0)
);

CREATE INDEX idx_mall_order_user_created_at
    ON mall_order (user_id, created_at);
CREATE INDEX idx_mall_order_status_created_at
    ON mall_order (status_code, created_at);
CREATE INDEX idx_mall_order_status_expires_at
    ON mall_order (status_code, expires_at);

CREATE TABLE mall_order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_title VARCHAR(100) NOT NULL,
    sku_code VARCHAR(64) NOT NULL,
    spec_text VARCHAR(200) NOT NULL,
    unit_price DECIMAL(12,2) NOT NULL,
    quantity INT NOT NULL,
    line_amount DECIMAL(12,2) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL,
    CONSTRAINT chk_mall_order_item_unit_price CHECK (unit_price > 0),
    CONSTRAINT chk_mall_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_mall_order_item_line_amount CHECK (line_amount > 0)
);

CREATE INDEX idx_mall_order_item_order_id
    ON mall_order_item (order_id);
CREATE INDEX idx_mall_order_item_sku_id
    ON mall_order_item (sku_id);



CREATE TABLE mall_payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_no VARCHAR(64) NOT NULL,
    order_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    amount DECIMAL(12,2) NOT NULL,
    status_code VARCHAR(20) NOT NULL,
    provider_transaction_no VARCHAR(64),
    callback_id VARCHAR(64),
    created_at TIMESTAMP(3) NOT NULL,
    updated_at TIMESTAMP(3) NOT NULL,
    paid_at TIMESTAMP(3),
    closed_at TIMESTAMP(3),
    CONSTRAINT uk_mall_payment_payment_no UNIQUE (payment_no),
    CONSTRAINT uk_mall_payment_order_id UNIQUE (order_id),
    CONSTRAINT uk_mall_payment_callback_id UNIQUE (callback_id),
    CONSTRAINT chk_mall_payment_amount CHECK (amount >= 0)
);
CREATE INDEX idx_mall_payment_user_created_at ON mall_payment (user_id, created_at);
CREATE INDEX idx_mall_payment_status_updated_at ON mall_payment (status_code, updated_at);
